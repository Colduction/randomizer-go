package randomizer

import (
	"math/bits"
	"math/rand/v2"
	"slices"
	"unsafe"
)

const (
	deci     string = "0123456789"
	octi     string = "01234567"
	lhexdict string = "0123456789abcdef"
	uhexdict string = "0123456789ABCDEF"
	lower    string = "abcdefghijklmnopqrstuvwxyz"
	upper    string = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
	alpha    string = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
	alnum    string = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
	base32   string = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
	base64u  string = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
)

// WordGenerator generates byte-oriented random words from a bound source.
// Its zero value uses the fast package source and [IndependentSymbols].
// Values may be shared concurrently; use [Generator.Word] to select another source.
// Custom dictionary positions have equal weight; repeated bytes increase their weight.
// Lengths count bytes, and custom dictionaries are not interpreted as UTF-8.
type WordGenerator struct {
	provider provider
	mode     WordMode
}

// Word generates words with the fast package source and [IndependentSymbols].
var Word WordGenerator

// WordMode controls dependence between successive generated bytes.
type WordMode uint8

const (
	// IndependentSymbols draws each byte independently with replacement.
	IndependentSymbols WordMode = iota

	// NoAdjacentRepeats excludes the preceding generated byte and renormalizes
	// the weights of the remaining bytes. The appended prefix is not considered.
	NoAdjacentRepeats
)

// Alphabet identifies a built-in byte alphabet used by [WordGenerator].
type Alphabet uint8

const (
	// DecimalAlphabet selects decimal digits 0-9.
	DecimalAlphabet Alphabet = iota

	// HexLowerAlphabet selects lowercase hexadecimal digits 0-9 and a-f.
	HexLowerAlphabet

	// HexUpperAlphabet selects uppercase hexadecimal digits 0-9 and A-F.
	HexUpperAlphabet

	// OctalAlphabet selects octal digits 0-7.
	OctalAlphabet

	// LowerAlphabet selects lowercase ASCII letters a-z.
	LowerAlphabet

	// UpperAlphabet selects uppercase ASCII letters A-Z.
	UpperAlphabet

	// AlphaAlphabet selects ASCII letters a-z and A-Z.
	AlphaAlphabet

	// AlphaNumericAlphabet selects ASCII digits and letters.
	AlphaNumericAlphabet

	// Base32Alphabet selects RFC 4648 base32 bytes without padding.
	Base32Alphabet

	// Base64URLAlphabet selects RFC 4648 URL-safe base64 bytes without padding.
	Base64URLAlphabet
)

type batchSpec struct {
	prod uint64
	k    uint8
}

func newBatchSpec(n uint64) batchSpec {
	if n < 2 {
		return batchSpec{prod: 1, k: 64}
	}
	prod, k := uint64(1), uint8(0)
	for {
		hi, lo := bits.Mul64(prod, n)
		if hi != 0 {
			break
		}
		prod, k = lo, k+1
	}
	for k > 1 && -prod%prod > 1<<60 {
		prod, k = prod/n, k-1
	}
	return batchSpec{prod: prod, k: k}
}

var batchSpecs = func() (specs [257]batchSpec) {
	for n := range specs {
		specs[n] = newBatchSpec(uint64(n))
	}
	return specs
}()

var alphabets = [...]string{
	DecimalAlphabet:      deci,
	HexLowerAlphabet:     lhexdict,
	HexUpperAlphabet:     uhexdict,
	OctalAlphabet:        octi,
	LowerAlphabet:        lower,
	UpperAlphabet:        upper,
	AlphaAlphabet:        alpha,
	AlphaNumericAlphabet: alnum,
	Base32Alphabet:       base32,
	Base64URLAlphabet:    base64u,
}

func alphabetData(alphabet Alphabet) string {
	if int(alphabet) < len(alphabets) {
		return alphabets[alphabet]
	}
	return deci
}

// WithMode returns a copy using the selected [WordMode].
// Unknown modes select [IndependentSymbols].
func (w WordGenerator) WithMode(mode WordMode) WordGenerator {
	if mode != NoAdjacentRepeats {
		mode = IndependentSymbols
	}
	w.mode = mode
	return w
}

// String returns a random string of the requested byte length.
// Nonpositive lengths return an empty string.
// Unknown alphabets select [DecimalAlphabet].
func (w WordGenerator) String(alphabet Alphabet, length int) string {
	out := w.Bytes(alphabet, length)
	return unsafe.String(unsafe.SliceData(out), len(out))
}

// Bytes returns newly owned random bytes of the requested length.
// Nonpositive lengths return nil. Unknown alphabets select [DecimalAlphabet].
func (w WordGenerator) Bytes(alphabet Alphabet, length int) []byte {
	return w.Append(nil, alphabet, length)
}

// Append appends random bytes without changing the existing prefix.
// It allocates only when the destination lacks capacity.
// Nonpositive lengths leave the destination unchanged.
// Unknown alphabets select [DecimalAlphabet].
func (w WordGenerator) Append(dst []byte, alphabet Alphabet, length int) []byte {
	if length <= 0 {
		return dst
	}
	offset := len(dst)
	dst = slices.Grow(dst, length)[:offset+length]
	session := openProvider(w.provider)
	defer session.close()
	if w.mode == NoAdjacentRepeats {
		fillBatchedNoRepeat(dst[offset:], alphabetData(alphabet), session.provider)
	} else {
		fillIndependent(dst[offset:], alphabetData(alphabet), session.provider)
	}
	return dst
}

// Custom returns a random string drawn from the weighted dictionary positions.
// Empty dictionaries and nonpositive lengths return an empty string.
// Under [NoAdjacentRepeats], a dictionary with one distinct byte cannot
// produce more than one byte and returns an empty string for longer requests.
func (w WordGenerator) Custom(dictionary string, length int) string {
	out := appendCustom(w, nil, dictionary, length)
	return unsafe.String(unsafe.SliceData(out), len(out))
}

// CustomFromBytes behaves like [WordGenerator.Custom] for a byte dictionary.
// The dictionary is not retained or modified.
func (w WordGenerator) CustomFromBytes(dictionary []byte, length int) string {
	out := appendCustom(w, nil, dictionary, length)
	return unsafe.String(unsafe.SliceData(out), len(out))
}

// CustomBytes behaves like [WordGenerator.Custom] and returns newly owned bytes.
// Requests that cannot produce a word return nil.
func (w WordGenerator) CustomBytes(dictionary []byte, length int) []byte {
	return appendCustom(w, nil, dictionary, length)
}

// CustomBytesFromString behaves like [WordGenerator.CustomBytes] for a string dictionary.
func (w WordGenerator) CustomBytesFromString(dictionary string, length int) []byte {
	return appendCustom(w, nil, dictionary, length)
}

// AppendCustom appends random bytes without changing the existing prefix.
// Requests rejected by [WordGenerator.Custom] leave the destination unchanged.
// It allocates only when the destination lacks capacity.
func (w WordGenerator) AppendCustom(dst []byte, dictionary string, length int) []byte {
	return appendCustom(w, dst, dictionary, length)
}

// AppendCustomFromBytes behaves like [WordGenerator.AppendCustom] for a byte dictionary.
// Dictionary and destination may overlap; sampling uses the original dictionary.
// The dictionary is not retained.
func (w WordGenerator) AppendCustomFromBytes(dst []byte, dictionary []byte, length int) []byte {
	return appendCustom(w, dst, dictionary, length)
}

func appendCustom[S ~string | ~[]byte](w WordGenerator, dst []byte, dictionary S, length int) []byte {
	if length <= 0 || len(dictionary) == 0 {
		return dst
	}
	var (
		snapshot   [256]byte
		cumulative [256]uint64
		distinct   int
	)
	weighted := w.mode == NoAdjacentRepeats || len(dictionary) > len(snapshot)
	first := dictionary[0]
	constant := true
	for i := range len(dictionary) {
		c := dictionary[i]
		if c != first {
			constant = false
		}
		if i < len(snapshot) {
			snapshot[i] = c
		}
		if weighted {
			if cumulative[c] == 0 {
				distinct++
			}
			cumulative[c]++
		}
	}
	if w.mode == NoAdjacentRepeats && distinct == 1 && length > 1 {
		return dst
	}
	weighted = len(dictionary) > len(snapshot) || w.mode == NoAdjacentRepeats && distinct != len(dictionary)
	if weighted {
		var total uint64
		distinct = 0
		for c := range len(cumulative) {
			weight := cumulative[c]
			if weight != 0 {
				total += weight
				snapshot[distinct] = byte(c)
				cumulative[distinct] = total
				distinct++
			}
		}
	}
	offset := len(dst)
	dst = slices.Grow(dst, length)[:offset+length]
	out := dst[offset:]
	if constant {
		for i := range out {
			out[i] = first
		}
		return dst
	}
	session := openProvider(w.provider)
	defer session.close()
	switch {
	case weighted:
		fillWeighted(out, snapshot[:distinct], cumulative[:distinct], w.mode == NoAdjacentRepeats, session.provider)
	case w.mode == NoAdjacentRepeats:
		fillBatchedNoRepeat(out, snapshot[:len(dictionary)], session.provider)
	default:
		fillIndependent(out, snapshot[:len(dictionary)], session.provider)
	}
	return dst
}

func fillIndependent[S ~string | ~[]byte](out []byte, dictionary S, p provider) {
	n := uint64(len(dictionary))
	if n == 1 {
		for i := range out {
			out[i] = dictionary[0]
		}
		return
	}
	_, fast := p.(fastProvider)
	if n&(n-1) == 0 {
		shift := uint(bits.TrailingZeros64(n))
		batch := 64 / int(shift)
		for i := 0; i < len(out); {
			var x uint64
			if fast {
				x = rand.Uint64()
			} else {
				x = p.Uint64()
			}
			end := i + min(batch, len(out)-i)
			for ; i < end; i++ {
				out[i] = dictionary[x&(n-1)]
				x >>= shift
			}
		}
		return
	}
	batch := int(batchSpecs[n].k)
	for i := 0; i < len(out); {
		var lo uint64
		if fast {
			lo = rand.Uint64()
		} else {
			lo = p.Uint64()
		}
		end := i + min(batch, len(out)-i)
		prod := uint64(1)
		for j := i; j < end; j++ {
			var hi uint64
			hi, lo = bits.Mul64(lo, n)
			prod *= n
			out[j] = dictionary[hi]
		}
		if lo >= prod || lo >= -prod%prod {
			i = end
		}
	}
}

func skipPast(idx, lastIdx uint64) uint64 {
	return uint64(int64(lastIdx-1-idx)>>63) & 1
}

func fillBatchedNoRepeat[S ~string | ~[]byte](out []byte, dictionary S, p provider) {
	if len(out) == 0 {
		return
	}
	n := uint64(len(dictionary))
	if n == 1 {
		out[0] = dictionary[0]
		return
	}
	lastIdx := boundedFrom(p.Uint64(), n, p)
	out[0] = dictionary[lastIdx]
	if len(out) == 1 {
		return
	}
	if n == 2 {
		for i := 1; i < len(out); i++ {
			lastIdx ^= 1
			out[i] = dictionary[lastIdx]
		}
		return
	}
	n--
	batch := int(batchSpecs[n].k)
	_, fast := p.(fastProvider)
	for i := 1; i < len(out); {
		var lo uint64
		if fast {
			lo = rand.Uint64()
		} else {
			lo = p.Uint64()
		}
		end := i + min(batch, len(out)-i)
		saved := lastIdx
		prod := uint64(1)
		for j := i; j < end; j++ {
			var hi uint64
			hi, lo = bits.Mul64(lo, n)
			prod *= n
			lastIdx = hi + skipPast(hi, lastIdx)
			out[j] = dictionary[lastIdx]
		}
		if lo >= prod || lo >= -prod%prod {
			i = end
		} else {
			lastIdx = saved
		}
	}
}

func cumulativeIndex(cumulative []uint64, rank uint64) int {
	low, high := 0, len(cumulative)
	for low < high {
		mid := int(uint(low+high) >> 1)
		if cumulative[mid] <= rank {
			low = mid + 1
		} else {
			high = mid
		}
	}
	return low
}

func fillWeighted(out, dictionary []byte, cumulative []uint64, noAdjacent bool, p provider) {
	total := cumulative[len(cumulative)-1]
	if len(dictionary) == 1 {
		for i := range out {
			out[i] = dictionary[0]
		}
		return
	}
	last := cumulativeIndex(cumulative, uniformUint64n(total, p))
	out[0] = dictionary[last]
	if noAdjacent && len(dictionary) == 2 {
		for i := 1; i < len(out); i++ {
			last ^= 1
			out[i] = dictionary[last]
		}
		return
	}
	for i := 1; i < len(out); i++ {
		var start, weight uint64
		if noAdjacent {
			if last > 0 {
				start = cumulative[last-1]
			}
			weight = cumulative[last] - start
		}
		rank := uniformUint64n(total-weight, p)
		if noAdjacent && rank >= start {
			rank += weight
		}
		last = cumulativeIndex(cumulative, rank)
		out[i] = dictionary[last]
	}
}
